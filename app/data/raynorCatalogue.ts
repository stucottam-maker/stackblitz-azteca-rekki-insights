function slugify(value: string) {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

export const raynorCatalogueItems = rawRaynorCatalogue
  .map((product) => ({
    id: `raynor-${slugify(product.sku || product.name)}`,
    ingredient: product.name,
    supplier: "Raynor Hygiene",
    supplierProduct: product.name,
    unit: product.unit,
    fallbackPrice: product.price,
    preferred: preferredRaynorCodes.has(product.sku),
    category: product.category,
    sku: product.sku || undefined,
    lastOrdered: product.lastOrdered || undefined,
  }))
  .sort(
    (a, b) =>
      Number(b.preferred) - Number(a.preferred) ||
      a.supplierProduct.localeCompare(b.supplierProduct)
  );

